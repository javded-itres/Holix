"""Keep a product's organization off the agent's file and shell tools.

Studio registers a product in one organization. Rewriting ``org_id`` inside
``.holix/project.json`` hides that product from the organization that owns it.
Moving a product is ``transfer_project``, not a file edit.
"""

from __future__ import annotations

import json
import re
from pathlib import Path

# Assignment (`d['org_id'] = …`, `.org_id =`, `.get("org_id") =`) and in-place
# rewriters (`sed`/`perl`/`jq`) that mention org_id. A print of the current
# value has no assignment, so it stays allowed.
_ORG_ASSIGN_RE = re.compile(
    r"""(?x)
    (?:
        \[['\"]org_id['\"]\]
        | \.org_id\b
        | \.get\(\s*['\"]org_id['\"]\s*\)
    )\s*=
    | \b(?:sed|perl)\b[^|;\n]*org_id
    | \bjq\b[^|;\n]*\\?\.org_id\s*=
    """
)


def project_json_org_change_reason(path: Path, new_text: str) -> str | None:
    """Reason to refuse a write, or None when org_id is unchanged or absent."""
    if path.name != "project.json" or path.parent.name != ".holix":
        return None
    if not path.is_file():
        return None
    try:
        old = json.loads(path.read_text(encoding="utf-8"))
        new = json.loads(new_text)
    except (OSError, UnicodeError, json.JSONDecodeError):
        return None
    if not isinstance(old, dict) or not isinstance(new, dict):
        return None
    old_org = str(old.get("org_id") or "").strip()
    new_org = str(new.get("org_id") or "").strip()
    if not old_org or not new_org or old_org == new_org:
        return None
    return (
        "Refusing to change org_id in .holix/project.json "
        f"({old_org} → {new_org}). The product stays in its organization. "
        "Do not edit this file to make it visible. Open that organization, "
        "or use the project transfer action."
    )


def project_org_command_blocked(command: str) -> tuple[bool, str]:
    """Block a shell snippet that assigns org_id on project.json."""
    text = command or ""
    if "project.json" not in text:
        return False, ""
    if _ORG_ASSIGN_RE.search(text) is None:
        return False, ""
    return True, (
        "Refusing to change org_id in .holix/project.json from the shell. "
        "The product stays in its organization. Open that organization, "
        "or use the project transfer action."
    )
